using System.Globalization;
using System.Text;

namespace Lvgl.Ui;

/// <summary>
/// Emits C# that rebuilds a <see cref="UiDocument"/> with the LVGL.Net widget API.
/// </summary>
/// <remarks>
/// <para>
/// The generated type is <c>partial</c> and calls a <c>partial void OnBuilt()</c> hook at the end
/// of <c>Build</c>. Application code puts event wiring and data binding in the other half of the
/// class, so regenerating the layout never overwrites hand-written logic.
/// </para>
/// <para>
/// Shared styles become <c>LvStyle</c> properties and TrueType fonts are loaded once and cached.
/// Both are owned by the generated object; its <c>Destroy()</c> deletes the widgets first and
/// frees the styles and fonts after, the order LVGL requires.
/// </para>
/// <para>
/// Framework types are written <c>global::</c>-qualified, so the output compiles whether or not
/// the consuming project enables implicit usings.
/// </para>
/// <para>
/// This produces a file to check in, not a compiler source generator: designer output is edited
/// through the designer, and having the code on disk keeps the build free of extra tooling.
/// </para>
/// </remarks>
public sealed class CSharpUiGenerator
{
    /// <summary>Namespace for the generated class. Omitted when null or empty.</summary>
    public string? Namespace { get; set; }

    /// <summary>Class name; defaults to the document name.</summary>
    public string? ClassName { get; set; }

    /// <summary>Access modifier of the generated class.</summary>
    public string AccessModifier { get; set; } = "public";

    /// <summary>Source file the code was generated from, mentioned in the header comment.</summary>
    public string? SourcePath { get; set; }

    /// <summary>
    /// Generates the C# source text.
    /// </summary>
    /// <exception cref="InvalidOperationException">The document has validation problems.</exception>
    public string Generate(UiDocument document)
    {
        ArgumentNullException.ThrowIfNull(document);

        var problems = document.Validate();
        if (problems.Count > 0)
        {
            throw new InvalidOperationException(
                "The layout cannot be generated until these problems are fixed:" +
                Environment.NewLine + string.Join(Environment.NewLine, problems.Select(p => "  - " + p)));
        }

        var className = Sanitize(ClassName ?? document.Name, "Screen");
        var nodes = document.Descendants().ToList();
        var usesFonts = nodes.Any(n => !string.IsNullOrWhiteSpace(n.Font)) || document.Styles.Any(s => !string.IsNullOrWhiteSpace(s.Font));
        var usesAssets = usesFonts || nodes.Any(n => n.Type == UiWidgetType.Image && !string.IsNullOrWhiteSpace(n.Source));
        var writer = new IndentedWriter();

        writer.Line("// <auto-generated />");
        writer.Line(SourcePath is null
            ? "// Generated by the LVGL.Net designer. Do not edit; regenerate instead."
            : $"// Generated by the LVGL.Net designer from {Path.GetFileName(SourcePath)}. Do not edit; regenerate instead.");
        writer.Line("// Event handlers and data binding belong in the other half of this partial class.");

        if (usesAssets)
        {
            writer.Line("// This layout uses asset files. Copy them to the output folder, e.g. in the .csproj:");
            writer.Line("//   <None Include=\"assets/**\" CopyToOutputDirectory=\"PreserveNewest\" />");
        }

        writer.Line("#nullable enable");
        writer.Line();
        writer.Line("using Lvgl;");
        writer.Line("using Lvgl.Drawing;");
        if (document.Styles.Count > 0) writer.Line("using Lvgl.Styling;");
        writer.Line("using Lvgl.Widgets;");
        writer.Line();

        if (!string.IsNullOrWhiteSpace(Namespace))
        {
            writer.Line($"namespace {Namespace};");
            writer.Line();
        }

        writer.Line($"/// <summary>Layout '{Escape(document.Name)}', generated from a designer document.</summary>");
        writer.Line($"{AccessModifier} partial class {className}");
        writer.OpenBrace();

        writer.Line("/// <summary>Width the layout was designed against.</summary>");
        writer.Line($"public const int DesignWidth = {document.Width};");
        writer.Line();
        writer.Line("/// <summary>Height the layout was designed against.</summary>");
        writer.Line($"public const int DesignHeight = {document.Height};");
        writer.Line();

        if (usesAssets)
        {
            writer.Line("/// <summary>Folder the layout's asset paths are relative to. Defaults to the application folder.</summary>");
            writer.Line("public static string AssetDirectory { get; set; } = global::System.AppContext.BaseDirectory;");
            writer.Line();
        }

        writer.Line("/// <summary>The container the layout was built into.</summary>");
        writer.Line("public LvObject Root { get; private set; } = null!;");
        writer.Line();
        writer.Line("private readonly global::System.Collections.Generic.List<LvObject> _built = [];");
        if (usesFonts) writer.Line("private readonly global::System.Collections.Generic.Dictionary<(string, int), LvFont> _fonts = [];");
        writer.Line();

        foreach (var style in document.Styles)
        {
            writer.Line($"/// <summary>The shared style '{Escape(style.Name)}'.</summary>");
            writer.Line($"public LvStyle {style.Name} {{ get; private set; }} = null!;");
            writer.Line();
        }

        foreach (var node in nodes.Where(n => !string.IsNullOrEmpty(n.Name)))
        {
            writer.Line($"/// <summary>The {node.Type} named '{Escape(node.Name!)}'.</summary>");
            writer.Line($"public {TypeName(node.Type)} {node.Name} {{ get; private set; }} = null!;");
            writer.Line();
        }

        writer.Line("/// <summary>Creates every widget of the layout.</summary>");
        writer.Line("/// <param name=\"parent\">Container to build into; null uses the active screen.</param>");
        writer.Line("public LvObject Build(LvObject? parent = null)");
        writer.OpenBrace();
        writer.Line("Root = parent ?? LvScreen.Active();");

        if (TryColorLiteral(document.BackgroundColor, out var screenBackground))
        {
            writer.Line($"Root.SetBackgroundColor({screenBackground});");
        }

        foreach (var style in document.Styles)
        {
            writer.Line();
            EmitStyle(writer, style);
        }

        var names = new UniqueNames();
        foreach (var node in document.Children)
        {
            writer.Line();
            Emit(writer, node, "Root", names, topLevel: true);
        }

        // Keyboards are connected last: a keyboard may name a field declared after it.
        var keyboards = nodes.Where(n => n.Type == UiWidgetType.Keyboard && !string.IsNullOrEmpty(n.Target)).ToList();
        if (keyboards.Count > 0) writer.Line();
        foreach (var keyboard in keyboards)
        {
            writer.Line($"{names.LocalFor(keyboard)}.TextArea = {keyboard.Target};");
        }

        writer.Line();
        writer.Line("OnBuilt();");
        writer.Line("return Root;");
        writer.CloseBrace();

        EmitDestroy(writer, document, usesFonts);

        if (usesAssets)
        {
            writer.Line();
            writer.Line("private static string Asset(string relativePath) => global::System.IO.Path.Combine(AssetDirectory, relativePath);");
        }

        if (usesFonts)
        {
            writer.Line();
            writer.Line("private LvFont Font(string relativePath, int size)");
            writer.OpenBrace();
            writer.Line("if (!_fonts.TryGetValue((relativePath, size), out var font))");
            writer.OpenBrace();
            writer.Line("font = LvFont.FromFile(Asset(relativePath), size);");
            writer.Line("_fonts[(relativePath, size)] = font;");
            writer.CloseBrace();
            writer.Line();
            writer.Line("return font;");
            writer.CloseBrace();
        }

        writer.Line();
        writer.Line("/// <summary>Called once the layout has been built. Implement it in your own partial half.</summary>");
        writer.Line("partial void OnBuilt();");

        writer.CloseBrace();

        return writer.ToString();
    }

    private static void EmitDestroy(IndentedWriter writer, UiDocument document, bool usesFonts)
    {
        writer.Line();
        writer.Line("/// <summary>");
        writer.Line("/// Deletes the widgets this layout built, then frees its styles and fonts - in that order,");
        writer.Line("/// because the widgets point at them.");
        writer.Line("/// </summary>");
        writer.Line("public void Destroy()");
        writer.OpenBrace();
        writer.Line("foreach (var widget in _built)");
        writer.OpenBrace();
        writer.Line("if (widget.IsAlive) widget.Delete();");
        writer.CloseBrace();
        writer.Line();
        writer.Line("_built.Clear();");

        foreach (var style in document.Styles) writer.Line($"{style.Name}?.Dispose();");

        if (usesFonts)
        {
            writer.Line();
            writer.Line("foreach (var font in _fonts.Values) font.Dispose();");
            writer.Line("_fonts.Clear();");
        }

        writer.CloseBrace();
    }

    private static void EmitStyle(IndentedWriter writer, UiStyle style)
    {
        writer.Line($"{style.Name} = new LvStyle();");

        if (TryColorLiteral(style.BackgroundColor, out var background)) writer.Line($"{style.Name}.BackgroundColor({background});");
        if (style.BackgroundOpacity is { } opacity) writer.Line($"{style.Name}.BackgroundOpacity({Math.Clamp(opacity, 0, 255)});");
        if (TryColorLiteral(style.TextColor, out var text)) writer.Line($"{style.Name}.TextColor({text});");
        if (TryColorLiteral(style.BorderColor, out var border)) writer.Line($"{style.Name}.BorderColor({border});");
        if (style.BorderWidth is { } borderWidth) writer.Line($"{style.Name}.BorderWidth({borderWidth});");
        if (style.Radius is { } radius) writer.Line($"{style.Name}.Radius({radius});");
        if (style.Padding is { } padding) writer.Line($"{style.Name}.Padding({padding});");

        if (!string.IsNullOrWhiteSpace(style.Font))
        {
            writer.Line($"{style.Name}.Font(Font({Literal(NormalizeAsset(style.Font))}, {style.FontSize ?? UiBuilder.DefaultTrueTypeSize}));");
        }
        else if (style.FontSize is { } fontSize)
        {
            writer.Line($"{style.Name}.FontSize({fontSize});");
        }
    }

    private void Emit(IndentedWriter writer, UiNode node, string parentExpression, UniqueNames names, bool topLevel)
    {
        var local = names.Next(node);

        writer.Line($"var {local} = {Construct(node, parentExpression)};");
        if (topLevel) writer.Line($"_built.Add({local});");

        EmitTypeProperties(writer, node, local);

        foreach (var style in node.Styles) writer.Line($"{local}.AddStyle({style});");

        if (node.Type is not (UiWidgetType.Tab or UiWidgetType.Tile))
        {
            if (node.Width is { } width && node.Height is { } height)
            {
                writer.Line($"{local}.SetSize({width}, {height});");
            }
            else
            {
                if (node.Width is { } onlyWidth) writer.Line($"{local}.Width = {onlyWidth};");
                if (node.Height is { } onlyHeight) writer.Line($"{local}.Height = {onlyHeight};");
            }

            if (node.Align is { } align) writer.Line($"{local}.Align(LvAlign.{align}, {node.X}, {node.Y});");
            else writer.Line($"{local}.SetPosition({node.X}, {node.Y});");
        }

        EmitCommonProperties(writer, node, local);

        if (!string.IsNullOrEmpty(node.Name)) writer.Line($"{node.Name} = {local};");

        foreach (var child in node.Children)
        {
            writer.Line();
            Emit(writer, child, local, names, topLevel: false);
        }
    }

    private static void EmitCommonProperties(IndentedWriter writer, UiNode node, string local)
    {
        if (TryColorLiteral(node.BackgroundColor, out var background)) writer.Line($"{local}.SetBackgroundColor({background});");
        if (TryColorLiteral(node.TextColor, out var text)) writer.Line($"{local}.SetTextColor({text});");
        if (TryColorLiteral(node.BorderColor, out var border)) writer.Line($"{local}.SetBorderColor({border});");

        if (node.Type != UiWidgetType.Led && TryColorLiteral(node.AccentColor, out var accent))
        {
            var (setter, part) = UiBuilder.AccentPart(node.Type);
            writer.Line($"{local}.{setter}({accent}, LvPart.{part});");
        }

        if (node.BorderWidth is { } borderWidth) writer.Line($"{local}.SetBorderWidth({borderWidth});");
        if (node.Radius is { } radius) writer.Line($"{local}.SetRadius({radius});");
        if (node.Padding is { } padding) writer.Line($"{local}.SetPadding({padding});");

        if (!string.IsNullOrWhiteSpace(node.Font))
        {
            writer.Line($"{local}.SetFont(Font({Literal(NormalizeAsset(node.Font))}, {node.FontSize ?? UiBuilder.DefaultTrueTypeSize}));");
        }
        else if (node.FontSize is { } fontSize)
        {
            writer.Line($"{local}.SetFontSize({fontSize});");
        }

        if (node.Hidden) writer.Line($"{local}.IsHidden = true;");
    }

    private static void EmitTypeProperties(IndentedWriter writer, UiNode node, string local)
    {
        switch (node.Type)
        {
            case UiWidgetType.Slider or UiWidgetType.Bar:
                if (node.Minimum is { } min && node.Maximum is { } max) writer.Line($"{local}.SetRange({min}, {max});");
                if (node.Value is { } value) writer.Line($"{local}.SetValue({value}, animate: false);");
                break;

            case UiWidgetType.Arc:
                if (node.Minimum is { } arcMin && node.Maximum is { } arcMax) writer.Line($"{local}.SetRange({arcMin}, {arcMax});");
                if (node.Value is { } arcValue) writer.Line($"{local}.Value = {arcValue};");
                break;

            case UiWidgetType.Chart:
                if (node.ChartType is { } chartType) writer.Line($"{local}.Type = LvChartType.{chartType};");
                if (node.PointCount is { } points and > 0) writer.Line($"{local}.PointCount = {points};");
                if (node.Minimum is { } chartMin && node.Maximum is { } chartMax)
                {
                    writer.Line($"{local}.SetRange(LvChartAxis.PrimaryY, {chartMin}, {chartMax});");
                }
                foreach (var series in node.SeriesColors)
                {
                    TryColorLiteral(series, out var literal);
                    writer.Line($"{local}.AddSeries({literal ?? "LvColor.Blue"});");
                }
                break;

            case UiWidgetType.Image:
                if (!string.IsNullOrEmpty(node.Symbol)) writer.Line($"{local}.SetSymbol(LvSymbols.{node.Symbol});");
                else if (!string.IsNullOrWhiteSpace(node.Source)) writer.Line($"{local}.SetFile(Asset({Literal(NormalizeAsset(node.Source))}));");
                if (node.Rotation is { } rotation) writer.Line($"{local}.Rotation = {rotation};");
                if (node.ImageScale is { } scale and > 0) writer.Line($"{local}.Scale = {scale};");
                break;

            case UiWidgetType.TabView:
                if (node.TabBarPosition is { } position and (LvDir.Top or LvDir.Bottom or LvDir.Left or LvDir.Right))
                {
                    writer.Line($"{local}.TabBarPosition = LvDir.{position};");
                }
                break;

            case UiWidgetType.List:
                foreach (var (isHeading, text) in node.ListEntries())
                {
                    writer.Line(isHeading ? $"{local}.AddText({Literal(text)});" : $"{local}.AddButton({Literal(text)});");
                }
                break;

            case UiWidgetType.Keyboard:
                if (node.KeyboardMode is { } mode) writer.Line($"{local}.Mode = LvKeyboardMode.{mode};");
                break;

            case UiWidgetType.Led:
                if (TryColorLiteral(node.AccentColor, out var ledColor)) writer.Line($"{local}.Color = {ledColor};");
                if (node.Value is { } brightness) writer.Line($"{local}.Brightness = {Math.Clamp(brightness, 0, 255)};");
                break;

            case UiWidgetType.Scale:
                var scaleMode = node.ScaleMode ?? LvScaleMode.HorizontalBottom;
                writer.Line($"{local}.Mode = LvScaleMode.{scaleMode};");
                if (scaleMode is LvScaleMode.RoundInner or LvScaleMode.RoundOuter)
                {
                    writer.Line($"{local}.AngleRange = 270;");
                    writer.Line($"{local}.Rotation = 135;");
                }
                if (node.Minimum is { } scaleMin && node.Maximum is { } scaleMax) writer.Line($"{local}.SetRange({scaleMin}, {scaleMax});");
                if (node.TickCount is { } ticks) writer.Line($"{local}.TotalTickCount = {ticks};");
                if (node.MajorTickEvery is { } every) writer.Line($"{local}.MajorTickEvery = {every};");
                writer.Line($"{local}.ShowLabels = true;");
                break;

            case UiWidgetType.Table:
                if (node.Options.Count > 0)
                {
                    var rows = node.TableRows().Select(row => "[" + string.Join(", ", row.Select(Literal)) + "]");
                    writer.Line($"{local}.SetRows([{string.Join(", ", rows)}]);");
                }
                break;

            case UiWidgetType.Spinbox:
                if (node.Digits is { } digits) writer.Line($"{local}.SetDigitFormat({digits}, {node.DecimalPlaces ?? 0});");
                else if (node.DecimalPlaces is { } places and > 0) writer.Line($"{local}.SetDigitFormat({Math.Max(5, places + 1)}, {places});");
                if (node.Minimum is { } spinMin && node.Maximum is { } spinMax) writer.Line($"{local}.SetRange({spinMin}, {spinMax});");
                if (node.Value is { } spinValue) writer.Line($"{local}.Value = {spinValue};");
                break;
        }
    }

    private static string Construct(UiNode node, string parent) => node.Type switch
    {
        UiWidgetType.Panel => $"new LvPanel({parent})",
        UiWidgetType.Label => $"new LvLabel({parent}, {Literal(node.Text)})",
        UiWidgetType.Button => $"new LvButton({parent}, {Literal(node.Text)})",
        UiWidgetType.Slider => $"new LvSlider({parent})",
        UiWidgetType.Bar => $"new LvBar({parent})",
        UiWidgetType.Arc => $"new LvArc({parent})",
        UiWidgetType.Switch => $"new LvSwitch({parent}) {{ IsOn = {Bool(node.Value is > 0)} }}",
        UiWidgetType.Checkbox => $"new LvCheckbox({parent}, {Literal(node.Text)}) {{ IsChecked = {Bool(node.Value is > 0)} }}",
        UiWidgetType.Dropdown => $"new LvDropdown({parent}) {{ Options = {StringArray(node.Options)} }}",
        UiWidgetType.Roller => $"new LvRoller({parent}) {{ Options = {StringArray(node.Options)} }}",
        UiWidgetType.TextArea => $"new LvTextArea({parent}) {{ Text = {Literal(node.Text)} }}",
        UiWidgetType.Chart => $"new LvChart({parent})",
        UiWidgetType.Image => $"new LvImage({parent})",
        UiWidgetType.TabView => $"new LvTabView({parent})",
        UiWidgetType.Tab => $"{parent}.AddTab({Literal(node.Text ?? node.Name ?? "Tab")})",
        UiWidgetType.List => $"new LvList({parent})",
        UiWidgetType.TileView => $"new LvTileView({parent})",
        UiWidgetType.Tile => $"{parent}.AddTile({node.Column ?? 0}, {node.Row ?? 0})",
        UiWidgetType.Keyboard => $"new LvKeyboard({parent})",
        UiWidgetType.Spinner => $"new LvSpinner({parent})",
        UiWidgetType.Led => $"new LvLed({parent})",
        UiWidgetType.Scale => $"new LvScale({parent})",
        UiWidgetType.Table => $"new LvTable({parent})",
        UiWidgetType.Spinbox => $"new LvSpinbox({parent})",
        _ => throw new NotSupportedException($"Unknown widget type {node.Type}."),
    };

    /// <summary>The LVGL.Net class a widget kind is generated as, e.g. <c>LvTabPage</c> for a tab.</summary>
    public static string TypeName(UiWidgetType type) => type switch
    {
        UiWidgetType.Panel => "LvPanel",
        UiWidgetType.Label => "LvLabel",
        UiWidgetType.Button => "LvButton",
        UiWidgetType.Slider => "LvSlider",
        UiWidgetType.Bar => "LvBar",
        UiWidgetType.Arc => "LvArc",
        UiWidgetType.Switch => "LvSwitch",
        UiWidgetType.Checkbox => "LvCheckbox",
        UiWidgetType.Dropdown => "LvDropdown",
        UiWidgetType.Roller => "LvRoller",
        UiWidgetType.TextArea => "LvTextArea",
        UiWidgetType.Chart => "LvChart",
        UiWidgetType.Image => "LvImage",
        UiWidgetType.TabView => "LvTabView",
        UiWidgetType.Tab => "LvTabPage",
        UiWidgetType.List => "LvList",
        UiWidgetType.TileView => "LvTileView",
        UiWidgetType.Tile => "LvTile",
        UiWidgetType.Keyboard => "LvKeyboard",
        UiWidgetType.Spinner => "LvSpinner",
        UiWidgetType.Led => "LvLed",
        UiWidgetType.Scale => "LvScale",
        UiWidgetType.Table => "LvTable",
        UiWidgetType.Spinbox => "LvSpinbox",
        _ => "LvObject",
    };

    /// <summary>Asset paths use forward slashes in generated code so the file reads the same everywhere.</summary>
    private static string NormalizeAsset(string path) => path.Replace('\\', '/');

    private static bool TryColorLiteral(string? text, out string? literal)
    {
        literal = null;
        if (string.IsNullOrWhiteSpace(text) || !Drawing.LvColor.TryParse(text, out var color)) return false;

        literal = $"LvColor.FromRgb(0x{color.Rgb:X6}u)";
        return true;
    }

    private static string Bool(bool value) => value ? "true" : "false";

    private static string StringArray(IReadOnlyList<string> values) =>
        values.Count == 0 ? "[]" : "[" + string.Join(", ", values.Select(Literal)) + "]";

    private static string Literal(string? value) => value is null ? "\"\"" : "\"" + Escape(value) + "\"";

    private static string Escape(string value) => value
        .Replace("\\", "\\\\", StringComparison.Ordinal)
        .Replace("\"", "\\\"", StringComparison.Ordinal)
        .Replace("\r", "\\r", StringComparison.Ordinal)
        .Replace("\n", "\\n", StringComparison.Ordinal);

    private static string Sanitize(string name, string fallback)
    {
        var builder = new StringBuilder(name.Length);
        foreach (var c in name)
        {
            if (char.IsLetterOrDigit(c) || c == '_') builder.Append(c);
        }

        if (builder.Length == 0) return fallback;
        if (char.IsDigit(builder[0])) builder.Insert(0, '_');

        return builder.ToString();
    }

    /// <summary>Allocates a unique, readable local variable name for each emitted widget.</summary>
    private sealed class UniqueNames
    {
        private readonly HashSet<string> _used = new(StringComparer.Ordinal);
        private readonly Dictionary<UiNode, string> _byNode = [];
        private int _counter;

        public string Next(UiNode node)
        {
            var seed = string.IsNullOrEmpty(node.Name)
                ? node.Type.ToString()
                : Sanitize(node.Name, node.Type.ToString());

            var candidate = char.ToLowerInvariant(seed[0]) + seed[1..];

            // A local that collides with the generated property of the same node would shadow it.
            if (string.Equals(candidate, node.Name, StringComparison.Ordinal)) candidate += "Widget";

            while (!_used.Add(candidate))
            {
                candidate = string.Create(CultureInfo.InvariantCulture, $"{seed.ToLowerInvariant()}{++_counter}");
            }

            _byNode[node] = candidate;
            return candidate;
        }

        public string LocalFor(UiNode node) => _byNode[node];
    }

    /// <summary>Minimal brace-aware writer, so the generated file is readable as checked-in source.</summary>
    private sealed class IndentedWriter
    {
        private readonly StringBuilder _builder = new(4096);
        private int _depth;

        public void Line(string text = "")
        {
            if (text.Length > 0) _builder.Append(' ', _depth * 4);
            _builder.AppendLine(text);
        }

        public void OpenBrace()
        {
            Line("{");
            _depth++;
        }

        public void CloseBrace()
        {
            _depth--;
            Line("}");
        }

        public override string ToString() => _builder.ToString();
    }
}
